def test_refresh_and_check_scope_interfaces_from_exports(tmp_path: Path) -> None:
    _create_nodes(tmp_path)
    foundation = FoundationService()
    provider = FakePublicDeclProvider(
        foundation,
        {
            "Main.Topic.Core": [
                DeclPublicView(
                    ref=DeclRef(repo=None, node="Main.Topic.Core", name="main_result", revision=1),
                    kind="theorem",
                    summary="Main theorem.",
                )
            ]
        },
    )
    export = ExportComponent(foundation=foundation, public_decl_provider=provider)
    component = NodeProjectionComponent(foundation=foundation, export=export)

    missing = component.check_interfaces_sync(tmp_path, node_path="Main.Topic")
    assert missing.ok
    assert missing.value is not None
    assert missing.value.passed is False
    assert missing.value.issues[0].kind == "interfaces_projection_missing"

    added = export.add_scope_export(tmp_path, scope_path="Main.Topic", decl_ref="Main.Topic.Core:main_result")
    assert added.ok

    synced = component.check_interfaces_sync(tmp_path, node_path="Main.Topic")
    assert synced.ok
    assert synced.value is not None
    assert synced.value.passed is True
    path = tmp_path / "Main" / "Topic" / "Interfaces.lean"
    assert "import Main.Topic.Core.Theorems.main_result" in path.read_text(encoding="utf-8")

    path.write_text("import Bad.Module\n", encoding="utf-8")
    stale = component.check_interfaces_sync(tmp_path, node_path="Main.Topic")
    assert stale.ok
    assert stale.value is not None
    assert stale.value.passed is False
    assert stale.value.issues[0].kind == "interfaces_projection_stale"
