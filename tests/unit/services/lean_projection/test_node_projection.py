from pathlib import Path

from lean_constellation.domain.refs import DeclRef
from lean_constellation.services.foundation import ServiceResult
from lean_constellation.services.foundation import FoundationContext, FoundationService, WriteMode
from lean_constellation.services.lean_projection import NodeProjectionComponent
from lean_constellation.services.node import DeclPublicView, ExportComponent, NodeContractSnapshot, NodeTreeComponent


class FakePublicDeclProvider:
    def __init__(self, foundation: FoundationService, decls: dict[str, list[DeclPublicView]]) -> None:
        self.foundation = foundation
        self.decls = decls

    def list_content_public_decls(self, repo_root: Path, *, node_path: str) -> ServiceResult[list[DeclPublicView]]:
        return self.foundation.ok(self.decls.get(node_path, []))


class FailingPublicDeclProvider:
    def __init__(self, foundation: FoundationService) -> None:
        self.foundation = foundation

    def list_content_public_decls(self, repo_root: Path, *, node_path: str) -> ServiceResult[list[DeclPublicView]]:
        del repo_root
        return self.foundation.fail(
            self.foundation.issue(
                "content_public_decl_provider_failed",
                "Public declaration provider failed.",
                object_ref=node_path,
            )
        )


def _create_nodes(tmp_path: Path) -> None:
    tree = NodeTreeComponent()
    assert tree.ensure_root_scope_node(tmp_path).ok
    assert tree.create_scope_node(tmp_path, path="Main.Topic", goal="Topic goal", boundary="Topic boundary").ok
    assert tree.create_scope_node(tmp_path, path="Main.Topic.Provider", goal="Provider goal", boundary="Provider boundary").ok
    assert tree.create_content_node(
        tmp_path,
        path="Main.Topic.Core",
        goal="Core goal",
        boundary="Core boundary",
        objective="Build core.",
        success_criteria="Core ready.",
    ).ok


def _update_core_contract(tmp_path: Path) -> None:
    foundation = FoundationService()
    ctx = FoundationContext(repo_root=tmp_path)
    path = foundation.node_contract_path(ctx, "Main.Topic.Core", 1)
    loaded = foundation.read_json(path, NodeContractSnapshot)
    assert loaded.ok and loaded.value is not None
    loaded.value.deps.extend(
        [
            {"target": {"repo": None, "node": "Main.Topic.Provider"}, "reason": "Use provider boundary."},
            {"target": {"repo": "OtherRepo", "node": "Main"}, "reason": "Use external repo boundary."},
            {"target": {"repo": None, "node": "Main.Topic.Core"}, "reason": "Self dependency should not import self."},
        ]
    )
    loaded.value.mathlib_modules.extend(
        [
            {"module": "Mathlib.Data.Finset.Basic", "reason": "Finite sums."},
            {"ref": {"module": "Mathlib.Topology.Basic"}, "reason": "Topology."},
            {"module": "Mathlib.Data.Finset.Basic", "reason": "Duplicate."},
        ]
    )
    saved = foundation.write_json_atomic(path, loaded.value, mode=WriteMode.UPDATE_EXISTING)
    assert saved.ok


def _core_contract(tmp_path: Path) -> NodeContractSnapshot:
    foundation = FoundationService()
    loaded = foundation.read_json(
        foundation.node_contract_path(FoundationContext(repo_root=tmp_path), "Main.Topic.Core", 1),
        NodeContractSnapshot,
    )
    assert loaded.ok and loaded.value is not None
    return loaded.value


def _save_core_contract(tmp_path: Path, snapshot: NodeContractSnapshot) -> None:
    foundation = FoundationService()
    saved = foundation.write_json_atomic(
        foundation.node_contract_path(FoundationContext(repo_root=tmp_path), "Main.Topic.Core", 1),
        snapshot,
        mode=WriteMode.UPDATE_EXISTING,
    )
    assert saved.ok


def test_render_prelude_from_node_deps_and_mathlib_modules(tmp_path: Path) -> None:
    _create_nodes(tmp_path)
    _update_core_contract(tmp_path)
    component = NodeProjectionComponent()

    rendered = component.render_prelude(tmp_path, node_path="Main.Topic.Core")

    assert rendered.ok
    assert rendered.value is not None
    assert "This file is generated by Lean Constellation." in rendered.value
    assert "Node: Main.Topic.Core" in rendered.value
    assert "import Main.Topic.Provider.Interfaces" in rendered.value
    assert "import OtherRepo.Main.Interfaces" in rendered.value
    assert "import Mathlib.Data.Finset.Basic" in rendered.value
    assert "import Mathlib.Topology.Basic" in rendered.value
    assert rendered.value.count("Mathlib.Data.Finset.Basic") == 1
    assert "import Main.Topic.Core.Interfaces" not in rendered.value


def test_render_prelude_rejects_invalid_import_module(tmp_path: Path) -> None:
    _create_nodes(tmp_path)
    snapshot = _core_contract(tmp_path)
    snapshot.mathlib_modules.append({"module": "Bad Module", "reason": "Invalid import."})
    _save_core_contract(tmp_path, snapshot)
    component = NodeProjectionComponent()

    rendered = component.render_prelude(tmp_path, node_path="Main.Topic.Core")

    assert not rendered.ok
    assert rendered.issues[0].kind == "prelude_import_invalid"


def test_refresh_prelude_changed_and_no_changed(tmp_path: Path) -> None:
    _create_nodes(tmp_path)
    _update_core_contract(tmp_path)
